/**
 * 겹침 경고 — **선점이 못 막는 종류의 중복**을 선점할 때 함께 알린다.
 *
 * ── 왜 이것이 따로 필요한가 ─────────────────────────────────────────────────
 *
 * 선점(claim)은 **"지금 이 순간 둘이 같은 파일을 열고 있다"** 를 막는다.
 * 그런데 2026-09-10 에 같은 일(사진첩 권한 문구 한 줄)을 세 사람이 다섯 시간
 * 안에 각각 만들었고, **셋 다 규칙을 어기지 않았다.** 각자 잡고 각자 반납해서
 * 겹친 순간이 한 번도 없었다. 둘은 버려졌다.
 *
 * 즉 선점은 **동시성**을 막는 장치지 **중복**을 막는 장치가 아니다.
 * 이 둘을 같은 것으로 여긴 것이 빈틈의 시작이었다.
 *
 * ── 구멍이 둘이고, 검사도 둘이어야 한다 ─────────────────────────────────────
 *
 * 그날의 두 중복은 **서로 다른 이유로** 났다. 하나로 묶으면 대책이 반만 듣는다.
 *
 *   가) **보이지 않는 창** — 누가 커밋한 때부터 그것이 파트 dev 에 합쳐질 때까지,
 *       그 일은 git 어디에도 없다. 그날은 55분이었다 (19:46 커밋 → 20:41 머지).
 *       그 사이에 시작한 사람은 **무엇을 해도 알 수 없다.** 파트 dev 를 최신으로
 *       받아도 없고, 최상위 main 에서 갈라져 나와도 없다 — 거기엔 더 없다.
 *       → `unmergedTouching` 이 잡는다.
 *
 *   나) **낡은 바탕** — 내 브랜치가 갈라져 나온 시점이 오래돼서, **이미 합쳐진**
 *       남의 작업조차 나에게는 안 보이는 상태.
 *       → `staleTouching` 이 잡는다.
 *
 * 실측으로 확인했다. 두 검사는 **정확히 엇갈린다** —
 * 뒤처짐 검사는 20:15 건을 못 잡고, 안 합쳐진 브랜치 검사는 22:31 건을 못 잡는다.
 * 그래서 둘 다 있어야 한다. (근거: axMap `docs/26.09/26.09.11/04-무엇으로-막나.md`)
 *
 * ── 🔴 왜 숫자를 경로로 자르는가 ────────────────────────────────────────────
 *
 * "내 바탕이 몇 커밋 뒤처졌나" 를 **쌩숫자로 쓰면 거짓말을 한다.**
 *
 *   | 그날 상황      | 쌩숫자      | 경로로 자른 숫자 | 진실                    |
 *   |---------------|------------|----------------|------------------------|
 *   | 20:13 (미리)   | 4 뒤처짐    | 0              | 위험이 저장소 **밖**에 있었다 |
 *   | 22:28 (예승)   | 32 뒤처짐   | 1              | **그 1개가 전부**였다      |
 *
 * 32 중 31 개는 내 파일과 상관없는 남의 화면 작업이었다. 쓸모 있는 신호는
 * **"내가 잡으려는 경로를 건드린 커밋이 몇 개인가"** 하나뿐이다.
 *
 * ── 🔴 왜 막지 않고 경고만 하는가 ───────────────────────────────────────────
 *
 * 이것은 **"겹쳤다" 가 아니라 "겹쳤을지도 모른다"** 이다. 같은 파일을 건드렸다고
 * 같은 일인 것은 아니다. 막으면 멀쩡한 작업이 자주 막히고, **자주 막히는 검사는
 * 사람이 끈다.** 그러면 0 이 된다 — 지켜지지 않는 규칙은 없는 규칙보다 나쁘다.
 *
 * 그리고 이 선택이 **판 번호를 정한다.** 어제 통과하던 것을 오늘 실패로 바꾸면
 * 맨 앞자리(major)를 올리고 먼저 알려야 한다 (팀 규칙 0.3). 경고는 그렇지 않다.
 *
 * ── 순수하게 둔다 ──────────────────────────────────────────────────────────
 *
 * 이 파일에는 git 호출도 파일 접근도 없다. 판정과 문장만 있다.
 * 실제로 git 을 부르는 것은 `bin/axmap.mjs` 의 `collectOverlap` 이다.
 * 이 저장소가 `mrtarget.mjs` · `governance.mjs` 에서 지켜 온 경계와 같다.
 */

import { levelOf } from './version.mjs'

/**
 * 이 브랜치에서 일할 때, **무엇과 견주어야 하는가.**
 *
 * 기능 브랜치(`feat/front/S15P21E201-241-…`)의 가운데 칸이 파트다.
 * 그 파트의 개발 브랜치(`front/dev`)가 "이미 된 일" 이 모이는 자리다.
 *
 * 🔴 **단계 판정은 `version.mjs` 의 `levelOf` 를 가져다 쓴다.** 여기서 다시
 *    만들면 한 저장소에 브랜치 단계 판정이 둘이 되고, `back/main` 이 최상위인지
 *    파트인지를 두 곳이 서로 다르게 답할 수 있다. `mrtarget.mjs` 가 같은 이유로
 *    같은 선택을 했다.
 *
 * 🔴 **그런데 파트 이름은 `partOf` 로 못 구한다.** `partOf` 는 *마지막* 슬래시
 *    앞을 준다 — `front/dev` → `front` 는 맞지만
 *    `feat/front/S15P21E201-241-photo` → `feat/front` 가 된다. 기능 브랜치의
 *    파트는 **가운데 칸**이다 (`[접두사]/[파트]/[Jira키]-[작업명]`, 팀 규칙 2절).
 *    그래서 여기서만 가운데 칸을 직접 읽는다. 이 차이를 모르고 `partOf` 를 쓰면
 *    `feat/front/dev` 라는 **있지도 않은 브랜치**와 견주게 되고, 그러면 검사는
 *    늘 조용해진다 — 가장 나쁜 고장이다(아무 말도 안 하니 아무도 모른다).
 *
 * 가운데 칸이 파트가 아닌 경우(팀 규칙이 경고하는 `feat/feat/…` 같은 오타)에는
 * 그 이름의 dev 브랜치가 **없어서** 부르는 쪽이 조용히 넘어간다. 억지로 고쳐
 * 맞히지 않는다 — 틀린 것과 견주느니 안 견주는 편이 낫다.
 *
 * ── 🔴 사다리가 없는 저장소도 있다 — 그래서 설정값을 받는다 ────────────────
 *
 * 이 검사를 만든 axMap 저장소 **자신이 첫 피해자였다.** axMap 의 개발선은
 * `team-sync` 한 줄이라 브랜치 이름에 **파트 칸이 아예 없다.** 그래서 위 규칙은
 * 늘 `null` 을 냈고, 검사는 **한 번도 돈 적이 없다.** 그러면서 아무 말도 안 하니
 * 아무도 그 사실을 몰랐다 — 이 파일이 계속 경계하는 그 고장이다.
 *
 * 고치는 길이 둘이었다.
 *
 *   가) **`core/dev` 같은 파트 브랜치를 새로 만든다.** 안 골랐다. 그러려면 개발선
 *       자체를 옮겨야 하고, 이미 나가 있는 브랜치·MR·CI 가 전부 따라와야 한다.
 *       **되돌리기 어려운 변경으로 검사 하나를 살리는 것은 값이 맞지 않는다.**
 *   나) ✅ **견줄 브랜치를 저장소가 직접 적게 한다** (git 설정값
 *       `axmap.comparebranch`). 브랜치 구조를 한 글자도 안 건드리고, 사다리가
 *       없는 **어느 저장소에서도** 이 검사가 돈다. 틀리면 설정값 한 줄을
 *       지우면 끝이라 **되돌리기도 공짜**다.
 *
 * 우선순위는 **파트 칸이 먼저, 설정값이 나중**이다. 팀 저장소처럼 사다리가 있는
 * 곳에서는 지금 동작이 그대로 남아야 하기 때문이다 — 설정값을 앞세우면 한 줄
 * 설정이 파트별 판정을 통째로 덮어써서, `feat/front/…` 도 `feat/back/…` 도
 * 같은 한 곳과 견주게 된다.
 *
 * 🔴 **지금 서 있는 브랜치가 곧 견줄 브랜치이면 `null` 이다.** 자기 자신과 견주면
 *    `HEAD..HEAD` 도 `--all --not HEAD HEAD` 도 언제나 비어서, 검사가 **도는
 *    것처럼 보이면서 아무것도 안 잡는다.** 안 도는 것보다 나쁘다 — 안 도는 줄
 *    알면 고치기라도 한다.
 *
 * 🔴 **설정값을 읽는 것은 여기가 아니다.** 이 파일에는 git 호출도 파일 접근도
 *    없다(머리말). `bin/axmap.mjs` 가 `git config --get axmap.comparebranch` 로
 *    읽어 **인자로 넘긴다.** `mrtarget.mjs` · `governance.mjs` 가 지켜 온 경계다.
 *
 * @param {string} branch 지금 체크아웃된 브랜치 이름
 * @param {string|null} [configured] 저장소가 적어 둔 견줄 브랜치
 *        (git 설정값 `axmap.comparebranch`). 없으면 null
 * @returns {string|null} 견줄 브랜치 이름(`front/dev`). 견줄 것이 없으면 null
 */
export function compareBranchFor(branch, configured = null) {
  const name = String(branch ?? '').trim()
  if (!name) return null

  // 이미 파트 dev 위에 있거나, 파트 브랜치·최상위에 있으면 견줄 위쪽이 없다.
  // "위쪽이 없다" 는 고장이 아니라 정상이므로 조용히 넘어간다.
  // 🔴 설정값이 있어도 여기서는 안 쓴다 — 이 자리들은 "못 읽었다" 가 아니라
  //    "위쪽이 없는 것이 맞다" 이고, 둘을 섞으면 파트 dev 가 자기 위의 아무 데나
  //    견주게 된다.
  const level = levelOf(name)
  if (level === 'dev' || level === 'func' || level === 'main') return null

  // ① `접두사/파트/작업명` 세 칸이 있으면 가운데 칸이 파트다.
  //    `hotfix/S15P21E201-33-…` 처럼 두 칸이면 파트가 적혀 있지 않다 — ② 로 간다.
  const segs = name.split('/').filter(Boolean)
  const part = segs.length >= 3 ? segs[1] : null

  // ② 파트를 못 읽었으면 저장소가 적어 둔 것을 쓴다. ③ 그것도 없으면 null.
  const cmp = part ? `${part}/dev` : String(configured ?? '').trim() || null
  if (!cmp) return null

  // 🔴 자기 자신과는 안 견준다. 견줘 봐야 늘 비어서, 있으나 마나 한 검사가 된다.
  if (cmp === name) return null

  return cmp
}

/**
 * 두 검사 결과를 사람이 읽는 경고로 바꾼다.
 *
 * 🔴 **겹치는 것이 없으면 아무것도 내지 않는다** (null 을 준다).
 *    선점은 하루에도 수십 번 도는 자리라, 평소에 조용한 것이 이 검사의 조건이다.
 *
 * @param {object} o
 * @param {string} o.compareBranch 견준 브랜치 (`origin/front/dev`)
 * @param {Array<{hash:string, who:string, subject:string}>} o.stale
 *        내 바탕 뒤로 이미 합쳐진 것 중, 내가 잡은 경로를 건드린 커밋
 * @param {Array<{hash:string, ref:string, who:string, subject:string}>} o.unmerged
 *        내가 잡은 경로를 건드렸지만 아직 그 브랜치에 안 합쳐진 커밋
 * @returns {string|null}
 */
export function formatOverlap({ compareBranch, stale = [], unmerged = [] }) {
  if (!stale.length && !unmerged.length) return null

  const L = []
  L.push('')
  L.push('  ── 겹칠지도 모릅니다 (막지는 않습니다) ─────────────────────────────')

  if (unmerged.length) {
    L.push('')
    L.push(`  [1] 이 경로를 이미 건드렸지만 ${compareBranch} 에 아직 없는 작업이 있습니다.`)
    L.push('      아직 합쳐지지 않아 최신으로 받아도 보이지 않습니다.')
    for (const c of unmerged) {
      L.push(`        · ${c.hash}  ${c.who}  ${c.subject}`)
      L.push(`          ↳ ${c.ref}`)
    }
  }

  if (stale.length) {
    L.push('')
    L.push(`  [2] ${compareBranch} 에는 이미 합쳐졌는데 내 바탕에는 없는 작업이 있습니다.`)
    L.push('      내 브랜치가 갈라져 나온 시점이 그보다 앞섭니다.')
    for (const c of stale) {
      L.push(`        · ${c.hash}  ${c.who}  ${c.subject}`)
    }
  }

  L.push('')
  L.push('  같은 일인지 먼저 보십시오. 같은 일이면 다시 만들지 말고 그것을 가져오십시오.')
  L.push('  ────────────────────────────────────────────────────────────────')
  return L.join('\n')
}
